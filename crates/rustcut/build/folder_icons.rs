//! Build-time table of the built-in folder pictures (P11.2, user decision Q-FP2: a curated set of about 200 Tabler
//! icons, not the whole library). Every SVG in `assets/folder-icons/` becomes one `(name, svg)` entry of
//! `folder_icons.rs` in `OUT_DIR`, sorted by name (the app looks names up with a binary search).

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const DIR_RELATIVE: &str = "assets/folder-icons";

pub fn generate(manifest_dir: &Path, out_dir: &Path) -> Result<(), String> {
    let dir = manifest_dir.join(DIR_RELATIVE);
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<(String, String)> = fs::read_dir(&dir)
        .map_err(|e| format!("cannot read {}: {e}", dir.display()))?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|e| e == "svg"))
        .filter_map(|path| {
            let name = path.file_stem()?.to_str()?.to_owned();
            Some((name, path.to_str()?.to_owned()))
        })
        .collect();
    names.sort();
    if names.is_empty() {
        return Err(format!("no SVG in {}", dir.display()));
    }
    let mut out = String::from(
        "// Generated by build/folder_icons.rs from assets/folder-icons/ - do not edit.\n\
         /// The built-in folder pictures: (Tabler name, SVG), sorted by name.\n\
         pub static FOLDER_ICONS: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &names {
        writeln!(out, "    ({name:?}, include_str!({path:?})),").map_err(|e| e.to_string())?;
    }
    out.push_str("];\n");
    fs::write(out_dir.join("folder_icons.rs"), out).map_err(|e| format!("cannot write folder_icons.rs: {e}"))
}
