//! The kit for writing RustCut plugins in Rust.
//!
//! A plugin is a library crate built for `wasm32-wasip2` as a `cdylib`. It implements [`Plugin`] and exports it:
//!
//! ```ignore
//! use rustcut_plugin_api::{Action, Context, Event, Issue, Plugin, export_plugin};
//!
//! struct Hello;
//!
//! impl Plugin for Hello {
//!     fn configure(_settings: String) -> Result<(), String> {
//!         Ok(())
//!     }
//!     fn handle(_event: Event, _context: Context) -> Result<Vec<Action>, String> {
//!         Ok(Vec::new())
//!     }
//!     fn check(_settings: String) -> Vec<Issue> {
//!         Vec::new()
//!     }
//! }
//!
//! export_plugin!(Hello);
//! ```
//!
//! Since API 1.2 a plugin may have commands (`[[commands]]` in `plugin.toml`, run by a key, a File menu entry or a
//! menu bar button): it implements [`Commands`] too and exports with `export_plugin_with_commands!` instead.
//!
//! The contract itself is `wit/rustcut-plugin.wit`; RustCut's `docs/plugins.md` explains the manifest, settings,
//! limits and errors.

#[doc(hidden)]
pub mod bindings {
    #![allow(
        unsafe_code,
        unsafe_op_in_unsafe_fn,
        clippy::pedantic,
        clippy::all,
        clippy::restriction,
        unused_qualifications,
        missing_docs,
        reason = "generated by wit-bindgen"
    )]

    wit_bindgen::generate!({
        path: "wit",
        world: "plugin",
        pub_export_macro: true,
        export_macro_name: "export_plugin",
        default_bindings_module: "rustcut_plugin_api::__bindings",
        generate_all,
    });
}

/// Since API 1.2: the world `plugin-with-commands`; its types and host functions are those of [`bindings`].
#[doc(hidden)]
pub mod commands_bindings {
    #![allow(
        unsafe_code,
        unsafe_op_in_unsafe_fn,
        clippy::pedantic,
        clippy::all,
        clippy::restriction,
        unused_qualifications,
        missing_docs,
        reason = "generated by wit-bindgen"
    )]

    wit_bindgen::generate!({
        path: "wit",
        world: "plugin-with-commands",
        pub_export_macro: true,
        export_macro_name: "__export_plugin_with_commands",
        default_bindings_module: "rustcut_plugin_api::__commands_bindings",
        with: {
            "rustcut:plugin/host@1.2.0": crate::bindings::rustcut::plugin::host,
            "rustcut:plugin/types@1.2.0": crate::bindings::rustcut::plugin::types,
        },
        generate_all,
    });

    /// A [`crate::Plugin`] is the world part of a plugin with commands.
    impl<T: crate::Plugin> Guest for T {
        fn configure(settings: String) -> Result<(), String> {
            <T as crate::Plugin>::configure(settings)
        }
        fn handle(event: crate::Event, context: crate::Context) -> Result<Vec<crate::Action>, String> {
            <T as crate::Plugin>::handle(event, context)
        }
        fn check(settings: String) -> Vec<crate::Issue> {
            <T as crate::Plugin>::check(settings)
        }
    }
}

