//! The kit for writing RustCut plugins in Rust.
//!
//! A plugin is a library crate built for `wasm32-wasip2` as a `cdylib`. It implements [`Plugin`] and exports it:
//!
//! ```ignore
//! use rustcut_plugin_api::{Action, Context, Event, Issue, Plugin, export_plugin};
//!
//! struct Hello;
//!
//! impl Plugin for Hello {
//!     fn configure(_settings: String) -> Result<(), String> {
//!         Ok(())
//!     }
//!     fn handle(_event: Event, _context: Context) -> Result<Vec<Action>, String> {
//!         Ok(Vec::new())
//!     }
//!     fn check(_settings: String) -> Vec<Issue> {
//!         Vec::new()
//!     }
//! }
//!
//! export_plugin!(Hello);
//! ```
//!
//! The contract itself is `wit/rustcut-plugin.wit`; RustCut's `docs/plugins.md` explains the manifest, settings,
//! limits and errors.

#[doc(hidden)]
pub mod bindings {
    #![allow(
        unsafe_code,
        unsafe_op_in_unsafe_fn,
        clippy::pedantic,
        clippy::all,
        clippy::restriction,
        unused_qualifications,
        missing_docs,
        reason = "generated by wit-bindgen"
    )]

    wit_bindgen::generate!({
        path: "wit",
        world: "plugin",
        pub_export_macro: true,
        export_macro_name: "export_plugin",
        default_bindings_module: "rustcut_plugin_api::__bindings",
        generate_all,
    });
}

#[doc(hidden)]
pub use bindings as __bindings;
pub use bindings::Guest as Plugin;
pub use bindings::export_plugin;
pub use bindings::rustcut::plugin::host::Level;
pub use bindings::rustcut::plugin::types::{
    Action, Context, Event, Issue, Notice, OpenedBy, Place, SetRating, SetTarget, Tag, Target,
};

/// The plugin API version this kit implements.
pub const API_VERSION: &str = "1.0.0";

/// Writes a line into the plugin log. Outside RustCut (native unit tests) it goes to stderr.
pub fn log(level: Level, message: &str) {
    #[cfg(target_arch = "wasm32")]
    bindings::rustcut::plugin::host::log(level, message);
    #[cfg(not(target_arch = "wasm32"))]
    eprintln!("[{level:?}] {message}");
}

/// Reads the settings JSON that RustCut passes to `configure` and `check` into the plugin's own type.
///
/// # Errors
/// The JSON's error as text, ready to be returned from `configure`.
pub fn parse_settings<T: serde::de::DeserializeOwned>(settings: &str) -> Result<T, String> {
    serde_json::from_str(settings).map_err(|err| format!("the settings cannot be read: {err}"))
}

impl Tag {
    /// The path from the root, joined with " › " (as RustCut shows it).
    #[must_use]
    pub fn path_label(&self) -> String {
        self.path.join(" › ")
    }
}

impl Notice {
    /// A message of `level` at `place`.
    #[must_use]
    pub fn new(place: Place, level: Level, title: impl Into<String>, detail: impl Into<String>) -> Self {
        Self {
            place,
            level,
            title: title.into(),
            detail: detail.into(),
        }
    }
}
