/// The plugin API version this kit implements.
pub const API_VERSION: &str = "1.2.0";

/// Writes a line into the plugin log. Outside RustCut (native unit tests) it goes to stderr.
pub fn log(level: Level, message: &str) {
    #[cfg(target_arch = "wasm32")]
    bindings::rustcut::plugin::host::log(level, message);
    #[cfg(not(target_arch = "wasm32"))]
    eprintln!("[{level:?}] {message}");
}

/// Since API 1.1: the id of the folder of Settings > Target Folders that is the target now (0 is "Next to the source"),
/// or `None` when the target is no folder of that list (a loaded job's own folder). Call it inside `handle`; outside
/// RustCut (native unit tests) it is `None`. A plugin that calls it needs `api = "1.1"` in its `plugin.toml`.
#[must_use]
pub fn target_folder() -> Option<u32> {
    #[cfg(target_arch = "wasm32")]
    return bindings::rustcut::plugin::host::target_folder();
    #[cfg(not(target_arch = "wasm32"))]
    None
}

/// Since API 1.1: the `SetTarget` and `SetRating` actions this call of `handle` returns get no plugin mark (RustCut
/// still applies them). Call it inside `handle`; outside RustCut (native unit tests) it does nothing. A plugin that
/// calls it needs `api = "1.1"` in its `plugin.toml`.
pub fn hide_marks() {
    #[cfg(target_arch = "wasm32")]
    bindings::rustcut::plugin::host::hide_marks();
}

/// Since API 1.2: the files of the open video's folder in the asked order. Call it inside `Commands::run`; outside
/// RustCut (native unit tests) it is an error. A plugin that calls it needs `api = "1.2"`.
///
/// # Errors
/// No video is open, the folder cannot be read, or the call is outside `run`.
pub fn list_folder(request: FolderRequest) -> Result<FolderListing, String> {
    #[cfg(target_arch = "wasm32")]
    return commands_bindings::rustcut::plugin::command_host::list_folder(request);
    #[cfg(not(target_arch = "wasm32"))]
    {
        let _ = request;
        Err("list-folder works only inside RustCut".to_owned())
    }
}

/// Since API 1.2: opens `path` in RustCut after `run` returned (like a dropped file). Outside RustCut it does nothing.
pub fn open_video(path: &str) {
    #[cfg(target_arch = "wasm32")]
    commands_bindings::rustcut::plugin::command_host::open_video(path);
    #[cfg(not(target_arch = "wasm32"))]
    let _ = path;
}

/// Since API 1.2: a short bubble at the menu bar button that ran the command (a toast when it ran by key or menu),
/// with the plugin's name in front. Outside RustCut it does nothing.
pub fn bubble(text: &str) {
    #[cfg(target_arch = "wasm32")]
    commands_bindings::rustcut::plugin::command_host::bubble(text);
    #[cfg(not(target_arch = "wasm32"))]
    let _ = text;
}

/// Reads the settings JSON that RustCut passes to `configure` and `check` into the plugin's own type.
///
/// # Errors
/// The JSON's error as text, ready to be returned from `configure`.
pub fn parse_settings<T: serde::de::DeserializeOwned>(settings: &str) -> Result<T, String> {
    serde_json::from_str(settings).map_err(|err| format!("the settings cannot be read: {err}"))
}

impl Tag {
    /// The path from the root, joined with " › " (as RustCut shows it).
    #[must_use]
    pub fn path_label(&self) -> String {
        self.path.join(" › ")
    }
}

impl Notice {
    /// A message of `level` at `place`.
    #[must_use]
    pub fn new(place: Place, level: Level, title: impl Into<String>, detail: impl Into<String>) -> Self {
        Self {
            place,
            level,
            title: title.into(),
            detail: detail.into(),
        }
    }
}

#[cfg(test)]
mod tests {
    /// The crate's version, `API_VERSION` and the WIT package version are one number (a tag plugin-api-v1.2.0 once
    /// shipped the crate as 1.1.0).
    #[test]
    fn one_version_everywhere() {
        assert_eq!(env!("CARGO_PKG_VERSION"), super::API_VERSION);
        let wit = include_str!("../wit/rustcut-plugin.wit");
        assert!(wit.contains(&format!("package rustcut:plugin@{};", super::API_VERSION)));
    }
}
